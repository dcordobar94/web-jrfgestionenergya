'use client'

import { useState, useEffect } from 'react'
import Image from 'next/image'
import { WHATSAPP_URL, COMPANY_NAME } from '@/lib/constants'

const navLinks = [
  { href: '#servicios', label: 'Servicios' },
  { href: '#como-trabajamos', label: 'Cómo Trabajamos' },
  { href: '#contacto', label: 'Contacto' },
]

export default function Navbar() {
  const [menuOpen, setMenuOpen] = useState(false)
  const [scrolled, setScrolled] = useState(false)

  useEffect(() => {
    const handleScroll = () => setScrolled(window.scrollY > 10)
    window.addEventListener('scroll', handleScroll, { passive: true })
    return () => window.removeEventListener('scroll', handleScroll)
  }, [])

  const closeMenu = () => setMenuOpen(false)

  return (
    <header
      className={`fixed top-0 left-0 right-0 z-50 transition-all duration-300 ${
        scrolled
          ? 'bg-brand-dark/95 backdrop-blur-md shadow-lg shadow-black/30 border-b border-brand-border'
          : 'bg-brand-dark border-b border-brand-border/50'
      }`}
    >
      <nav
        className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 flex items-center justify-between h-16"
        aria-label="Navegación principal"
      >
        {/* Logo */}
        <a
          href="#"
          className="flex items-center gap-2 hover:opacity-90 transition-opacity"
          aria-label={`${COMPANY_NAME} — Inicio`}
        >
          <Image
            src="/images/logo_jrf.png"
            alt={`Logo ${COMPANY_NAME}`}
            width={64}
            height={64}
            className="object-contain"
            priority
          />
          <span className="hidden sm:inline text-brand-text font-bold text-lg">{COMPANY_NAME}</span>
          <span className="sm:hidden text-brand-text font-bold text-base">JRF Energya</span>
        </a>

        {/* Desktop nav */}
        <div className="hidden md:flex items-center gap-8">
          {navLinks.map((link) => (
            <a
              key={link.href}
              href={link.href}
              className="text-brand-muted hover:text-brand-secondary text-sm font-medium transition-colors"
            >
              {link.label}
            </a>
          ))}
          <a
            href={WHATSAPP_URL}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex items-center gap-2 bg-brand-secondary hover:bg-brand-bright text-brand-dark font-semibold text-sm px-4 py-2 rounded-full transition-colors"
            aria-label="Contactar por WhatsApp"
          >
            <WhatsAppIcon className="w-4 h-4" />
            Contactar por WhatsApp
          </a>
        </div>

        {/* Mobile hamburger */}
        <button
          type="button"
          className="md:hidden text-brand-text p-2 rounded-md focus:outline-none focus:ring-2 focus:ring-brand-secondary"
          onClick={() => setMenuOpen((v) => !v)}
          aria-label={menuOpen ? 'Cerrar menú' : 'Abrir menú'}
          aria-expanded={menuOpen}
        >
          {menuOpen ? (
            <svg xmlns="http://www.w3.org/2000/svg" className="w-6 h-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          ) : (
            <svg xmlns="http://www.w3.org/2000/svg" className="w-6 h-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M4 6h16M4 12h16M4 18h16" />
            </svg>
          )}
        </button>
      </nav>

      {/* Mobile menu */}
      {menuOpen && (
        <div className="md:hidden bg-brand-dark border-t border-brand-border px-4 py-4 flex flex-col gap-4">
          {navLinks.map((link) => (
            <a
              key={link.href}
              href={link.href}
              onClick={closeMenu}
              className="text-brand-muted hover:text-brand-secondary text-base font-medium transition-colors py-1"
            >
              {link.label}
            </a>
          ))}
          <a
            href={WHATSAPP_URL}
            target="_blank"
            rel="noopener noreferrer"
            onClick={closeMenu}
            className="inline-flex items-center justify-center gap-2 bg-brand-secondary hover:bg-brand-bright text-brand-dark font-semibold px-4 py-3 rounded-full transition-colors"
            aria-label="Contactar por WhatsApp"
          >
            <WhatsAppIcon className="w-5 h-5" />
            Contactar por WhatsApp
          </a>
        </div>
      )}
    </header>
  )
}

